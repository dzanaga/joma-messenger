#!/usr/bin/env python3
"""Restore from the GitHub backup on the phone (plan A1): hook JomaRestoreActivity (the
overlay) into the account wizard.

- the GitHub App's client ID (crates/joma/github-app.json, public) as a string resource;
- the activity in the manifest;
- a "restore from your GitHub backup" button under "import from backup" on the wizard's
  first screen;
- BouncyCastle's provider for Argon2id (already in the build's dependency cache).

Usage: restore.py <jami-android work dir> <github-app.json>
"""
import json
import sys
from pathlib import Path


def edit(path: Path, old: str, new: str):
    s = path.read_text()
    if new in s:
        return
    assert s.count(old) == 1, (str(path), s.count(old), old[:80])
    path.write_text(s.replace(old, new))


def main():
    work, app_json = Path(sys.argv[1]), Path(sys.argv[2])
    client_id = json.loads(app_json.read_text())["client_id"]
    values = work / "joma/res/values"
    values.mkdir(parents=True, exist_ok=True)
    (values / "joma_github.xml").write_text(
        '<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by android/tools/restore.py from crates/joma/github-app.json. -->\n'
        f'<resources>\n    <string name="joma_github_client_id" translatable="false">{client_id}</string>\n</resources>\n'
    )
    edit(work / "app/src/main/AndroidManifest.xml",
         '        <activity\n            android:name=".client.LogsActivity"',
         '        <activity\n'
         '            android:name="cx.ring.joma.JomaRestoreActivity"\n'
         '            android:exported="false"\n'
         '            android:label="@string/joma_restore_title"\n'
         '            android:theme="@style/AppTheme" />\n'
         '        <activity\n            android:name=".client.LogsActivity"')
    edit(work / "app/src/main/res/layout/frag_acc_home_create.xml",
         '            <com.google.android.material.button.MaterialButton\n                android:id="@+id/account_connect_server"',
         '            <com.google.android.material.button.MaterialButton\n'
         '                android:id="@+id/joma_restore_github"\n'
         '                style="@style/ButtonOutLined"\n'
         '                android:layout_width="@dimen/wizard_button_width"\n'
         '                android:layout_height="wrap_content"\n'
         '                android:layout_gravity="center"\n'
         '                android:text="@string/joma_restore_button"\n'
         '                android:drawableLeft="@drawable/baseline_backup_black_36"\n'
         '                android:drawableRight="@drawable/baseline_arrow_forward_black_18"/>\n\n'
         '            <com.google.android.material.button.MaterialButton\n                android:id="@+id/account_connect_server"')
    edit(work / "app/src/main/java/cx/ring/account/HomeAccountCreationFragment.kt",
         "            ringImportAccount.setOnClickListener { presenter.clickOnBackupAccountLink() }\n",
         "            ringImportAccount.setOnClickListener { presenter.clickOnBackupAccountLink() }\n"
         "            jomaRestoreGithub.setOnClickListener { startActivity(android.content.Intent(requireContext(), cx.ring.joma.JomaRestoreActivity::class.java)) }\n")
    edit(work / "app/build.gradle.kts",
         "    implementation(libs.kotlin.stdlib)\n",
         "    implementation(libs.kotlin.stdlib)\n    implementation(\"org.bouncycastle:bcprov-jdk18on:1.80.2\") // joma: Argon2id for the GitHub restore\n")
    # Joma's archives have no password: go straight on.
    edit(work / "app/src/main/java/cx/ring/account/JamiImportBackupFragment.kt",
         "        binding = this\n    }.root\n",
         "        binding = this\n"
         "        if (model.model.archive?.path?.contains(\"/joma-restore/\") == true) root.post { createAccount() }\n"
         "    }.root\n")
    print("restore: hooked")


if __name__ == "__main__":
    main()
