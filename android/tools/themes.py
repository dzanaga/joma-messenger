#!/usr/bin/env python3
"""Omarchy's themes inside joma for Android, switched at runtime (discussion
2026-11-27-one-joma, questions 3 and 9: themes cooked into the app; with an Omarchy
desktop, an option to follow it).

Android resources are fixed at build time, so the colours brand.py writes become theme
attributes:

1. every Joma colour role (the names brand.py's `night()` gives values) gets an attribute
   `jc_<name>`, and every Omarchy theme a style `JomaPalette.<Name>` that sets them all
   (the roles of brand.py, so each theme looks the way the desktop draws it);
2. references `@color/<name>` in layouts, drawables, colour lists, menus and styles
   become `?attr/jc_<name>` (colour definitions stay: they hold the build's palette, the
   fallback);
3. Kotlin's `ContextCompat.getColor(ctx, R.color.<name>)` and `<ctx>.getColor(R.color.
   <name>)` go through `JomaPalette.color`, which reads the attribute from the context's
   theme;
4. `JomaPaletteTable.kt` lists the themes (name, light or dark, style) and the colour to
   attribute map; `JomaPalette.kt` (the overlay) applies the chosen style to every
   activity before it draws, and keeps the choice;
5. small edits hook it in: the application installs it, the settings page gets a
   "theme" row, an account message from your own desktop (`application/x-joma-theme+json`)
   switches to its theme when "same as my Omarchy desktop" is chosen.

Usage: themes.py <jami-android work dir> <themes dir> <brand.py> [current colors.toml] [current name]
"""
import importlib.util
import re
import sys
from pathlib import Path


def load_brand(path: Path):
    spec = importlib.util.spec_from_file_location("brand", path)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def style_name(theme: str) -> str:
    return "JomaPalette_" + "".join(p.capitalize() for p in re.split(r"[^A-Za-z0-9]+", theme) if p)


def mode_of(text: str) -> str:
    m = re.search(r'^\s*mode\s*=\s*"(\w+)"', text, re.M)
    return m.group(1) if m else "dark"


def edit(path: Path, old: str, new: str):
    s = path.read_text()
    if new in s:
        return
    assert s.count(old) == 1, (str(path), s.count(old), old[:80])
    path.write_text(s.replace(old, new))


def main():
    work, themes_dir, brand_py = Path(sys.argv[1]), Path(sys.argv[2]), Path(sys.argv[3])
    brand = load_brand(brand_py)
    joma_theme_src = Path(brand_py).resolve().parents[2] / "crates/joma-theme/src/lib.rs"
    default = brand.palette(joma_theme_src.read_text())
    themes = {}
    for f in sorted(themes_dir.glob("*.toml")):
        themes[f.stem] = f.read_text()
    if len(sys.argv) > 5 and Path(sys.argv[4]).is_file() and sys.argv[5] and sys.argv[5] not in themes:
        themes[sys.argv[5]] = Path(sys.argv[4]).read_text()
    roles = list(brand.night(default).keys())
    keep_literal = {"ic_launcher_background", "joma_lavender"}
    roles = [r for r in roles if r not in keep_literal]
    res = work / "joma/res"
    app_res = work / "app/src/main/res"

    # 1. Attributes and one style per theme.
    attrs = "\n".join(f'    <attr name="jc_{r}" format="color|reference" />' for r in roles)
    (res / "values").mkdir(parents=True, exist_ok=True)
    styles = []
    table = []
    for name, text in themes.items():
        p = brand.parse_toml(text, default)
        colors = brand.night(p)
        items = "\n".join(f'        <item name="jc_{r}">{colors[r]}</item>' for r in roles)
        styles.append(f'    <style name="{style_name(name)}">\n{items}\n    </style>')
        bg = colors["background"]
        table.append((name, mode_of(text), style_name(name), bg, colors["colorPrimary"]))
    (res / "values" / "joma_palettes.xml").write_text(
        '<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by android/tools/themes.py from android/themes. -->\n'
        f"<resources>\n{attrs}\n" + "\n".join(styles) + "\n</resources>\n"
    )

    # 1b. The app's own themes (those built on a platform theme) give every attribute its
    # colour resource, so with no theme chosen everything looks as built (day and night).
    defaults = "".join(f'\n        <item name="jc_{r}">@color/{r}</item>' for r in roles)
    roots = 0
    for root in (app_res, res):
        for f in root.glob("values*/*.xml"):
            text = f.read_text()
            if "<style" not in text or f.name == "joma_palettes.xml":
                continue
            def add(m):
                nonlocal roots
                head = m.group(0)
                if not head.endswith("/>") and re.search(r'parent="(@style/)?(Theme\.|Base\.Theme|Platform\.)', head) and "jc_" not in head:
                    roots += 1
                    return head + defaults
                return head
            new = re.sub(r'<style\b[^>]*name="[^"]*"[^>]*>', add, text)
            if new != text:
                f.write_text(new)
    print(f"root themes given defaults: {roots}")

    # 2. @color/<role> → ?attr/jc_<role> in layouts, drawables, colour lists, menus, styles.
    pat = re.compile(r"@color/(" + "|".join(sorted(roles, key=len, reverse=True)) + r")\b")
    changed = 0
    for root in (app_res, res):
        for f in root.rglob("*.xml"):
            rel = f.relative_to(root).parts
            folder = rel[0]
            if folder.startswith("values"):
                text = f.read_text()
                if "<style" not in text or f.name in ("joma_colors.xml", "joma_palettes.xml"):
                    continue
                # Only inside <item> of styles; colour definitions keep their values.
                new = re.sub(r"(<item\b[^>]*>)([^<]*)(</item>)", lambda m: m.group(0) if 'name="jc_' in m.group(1) else m.group(1) + pat.sub(r"?attr/jc_\1", m.group(2)) + m.group(3), text)
            elif folder.split("-")[0] in ("layout", "drawable", "color", "menu", "anim", "animator"):
                if f.name.startswith("ic_launcher"):
                    continue
                text = f.read_text()
                new = pat.sub(r"?attr/jc_\1", text)
            else:
                continue
            if new != text:
                f.write_text(new)
                changed += 1

    # 3. Colours read in code.
    java = work / "app/src/main/java"
    code = 0
    rk = "|".join(sorted(roles, key=len, reverse=True))
    p1 = re.compile(r"ContextCompat\.getColor\(\s*([^,()]+(?:\([^()]*\))?)\s*,\s*R\.color\.(" + rk + r")\s*\)")
    p2 = re.compile(r"(?<![\w.])(context|requireContext\(\)|this|it|ctx|view\.context|itemView\.context|binding\.root\.context|root\.context|activity|requireActivity\(\))\.getColor\(\s*R\.color\.(" + rk + r")\s*\)")
    p4 = re.compile(r"(?<![\w.])(context|requireContext\(\)|this|it|ctx|view\.context|itemView\.context|binding\.root\.context|root\.context|activity|requireActivity\(\))\.getColorStateList\(\s*R\.color\.(" + rk + r")\s*\)")
    p3 = re.compile(r"ContextCompat\.getColorStateList\(\s*([^,()]+(?:\([^()]*\))?)\s*,\s*R\.color\.(" + rk + r")\s*\)")
    for f in java.rglob("*.kt"):
        if "joma" in f.parts:
            continue
        text = f.read_text()
        new = p1.sub(r"cx.ring.joma.JomaPalette.color(\1, R.color.\2)", text)
        new = p2.sub(r"cx.ring.joma.JomaPalette.color(\1, R.color.\2)", new)
        new = p3.sub(r"cx.ring.joma.JomaPalette.colors(\1, R.color.\2)", new)
        new = p4.sub(r"cx.ring.joma.JomaPalette.colors(\1, R.color.\2)", new)
        if new != text:
            f.write_text(new)
            code += 1

    # 4. The table.
    out = java / "cx/ring/joma"
    out.mkdir(parents=True, exist_ok=True)
    rows = ",\n".join(f'        Theme("{n}", {"false" if m == "light" else "true"}, R.style.{s}, 0xFF{bg[1:]}.toInt(), 0xFF{acc[1:]}.toInt())' for n, m, s, bg, acc in table)
    pairs = ",\n".join(f"        R.color.{r} to R.attr.jc_{r}" for r in roles)
    (out / "JomaPaletteTable.kt").write_text(
        "// Generated by android/tools/themes.py from android/themes: do not edit.\n"
        "package cx.ring.joma\n\nimport cx.ring.R\n\n"
        "data class Theme(val name: String, val dark: Boolean, val style: Int, val background: Int, val accent: Int)\n\n"
        "object JomaPaletteTable {\n"
        f"    val themes = listOf(\n{rows}\n    )\n\n"
        f"    val attrOf: Map<Int, Int> = mapOf(\n{pairs}\n    )\n"
        "}\n"
    )

    # 5. Hooks.
    edit(work / "app/src/main/java/cx/ring/application/JamiApplication.kt",
         "        instance = this\n        setupActivityListener()\n",
         "        instance = this\n        cx.ring.joma.JomaPalette.install(this)\n        setupActivityListener()\n")
    edit(work / "libjamiclient/src/main/kotlin/net/jami/services/AccountService.kt",
         "    fun incomingAccountMessage(accountId: String, messageId: String?, callId: String?, from: String, messages: Map<String, String>) {\n",
         "    /** joma: your own desktop's theme (application/x-joma-theme+json). */\n"
         "    var jomaTheme: ((accountId: String, from: String, json: String) -> Unit)? = null\n\n"
         "    fun incomingAccountMessage(accountId: String, messageId: String?, callId: String?, from: String, messages: Map<String, String>) {\n"
         "        messages[\"application/x-joma-theme+json\"]?.let { jomaTheme?.invoke(accountId, from, it); return }\n")
    edit(work / "app/src/main/java/cx/ring/services/SharedPreferencesServiceImpl.kt",
         "    override fun loadDarkMode() {\n        applyDarkMode(darkMode)\n",
         "    override fun loadDarkMode() {\n        // joma: the theme decides light or dark.\n        applyDarkMode(cx.ring.joma.JomaPalette.isDark(context) ?: darkMode)\n")
    edit(work / "app/src/main/java/cx/ring/settings/SettingsFragment.kt",
         "            settingsDarkTheme.setOnCheckedChangeListener { _, isChecked: Boolean ->\n",
         "            cx.ring.joma.JomaPalette.bindRow(requireActivity(), jomaPaletteRow, jomaPaletteValue)\n"
         "            settingsDarkThemeLayout.visibility = View.GONE\n"
         "            settingsDarkTheme.setOnCheckedChangeListener { _, isChecked: Boolean ->\n")
    edit(app_res / "layout/frag_settings.xml",
         '            <RelativeLayout\n                android:id="@+id/settings_dark_theme_layout"',
         '            <RelativeLayout\n'
         '                android:id="@+id/joma_palette_row"\n'
         '                android:layout_width="match_parent"\n'
         '                android:layout_height="wrap_content"\n'
         '                android:padding="@dimen/padding_large"\n'
         '                android:background="?attr/selectableItemBackground"\n'
         '                style="@style/CustomRelativeLayout">\n\n'
         '                <ImageView\n'
         '                    android:id="@+id/joma_palette_image"\n'
         '                    android:layout_width="wrap_content"\n'
         '                    android:layout_height="wrap_content"\n'
         '                    android:layout_alignParentStart="true"\n'
         '                    android:layout_centerVertical="true"\n'
         '                    android:contentDescription="@string/joma_theme"\n'
         '                    android:src="@drawable/baseline_invert_colors_24"\n'
         '                    android:layout_marginEnd="16dp"/>\n\n'
         '                <TextView\n'
         '                    android:id="@+id/joma_palette_title"\n'
         '                    style="@style/ListPrimary"\n'
         '                    android:layout_width="match_parent"\n'
         '                    android:layout_height="wrap_content"\n'
         '                    android:text="@string/joma_theme"\n'
         '                    android:layout_toEndOf="@id/joma_palette_image" />\n\n'
         '                <TextView\n'
         '                    android:id="@+id/joma_palette_value"\n'
         '                    style="@style/ListSecondary"\n'
         '                    android:layout_width="match_parent"\n'
         '                    android:layout_height="wrap_content"\n'
         '                    android:layout_toEndOf="@id/joma_palette_image"\n'
         '                    android:layout_below="@id/joma_palette_title" />\n'
         '            </RelativeLayout>\n\n'
         '            <RelativeLayout\n                android:id="@+id/settings_dark_theme_layout"')
    print(f"themes: {len(themes)}; xml files changed: {changed}; kotlin files: {code}")


if __name__ == "__main__":
    main()
